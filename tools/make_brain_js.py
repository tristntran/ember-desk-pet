#!/usr/bin/env python3
"""Wrap core/ (compiled to WebAssembly) into brain.js: one script tag, works from file:// and the artifact link.
Usage: python3 tools/make_brain_js.py target/wasm32-unknown-unknown/release/ember_core.wasm > brain.js"""
import base64, hashlib, sys
wasm = open(sys.argv[1], 'rb').read()
b64 = base64.b64encode(wasm).decode()
print(f"""// GENERATED by tools/make_brain_js.py from core/ (Rust → WebAssembly). Don't edit; edit core/src/lib.rs.
// sha256 {hashlib.sha256(wasm).hexdigest()[:16]} · {len(wasm)} bytes
(function(){{
  const B64="{b64}";
  let ex=null; const enc=new TextEncoder(), dec=new TextDecoder();
  async function load(){{
    if(ex) return true;
    const s=atob(B64), u=new Uint8Array(s.length); for(let i=0;i<s.length;i++) u[i]=s.charCodeAt(i);
    const {{instance}}=await WebAssembly.instantiate(u,{{}}); ex=instance.exports; return true;
  }}
  function call(req){{
    const b=enc.encode(JSON.stringify(req)), p=ex.alloc(b.length);
    new Uint8Array(ex.memory.buffer,p,b.length).set(b); ex.call(p,b.length); ex.dealloc(p,b.length);
    return JSON.parse(dec.decode(new Uint8Array(ex.memory.buffer,ex.out_ptr(),ex.out_len())));
  }}
  window.EmberBrain={{load,call,version:"{hashlib.sha256(wasm).hexdigest()[:16]}"}};
}})();""")
